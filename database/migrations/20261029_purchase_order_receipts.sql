create table if not exists public.purchase_order_receipts (
  id bigint generated by default as identity primary key,
  purchase_order_id bigint not null references public.purchase_orders(id),
  idempotency_key text not null unique,
  received_at timestamptz not null default now(),
  quantities jsonb not null
);

alter table public.purchase_order_receipts enable row level security;

comment on table public.purchase_order_receipts is
  'Immutable receipt batches applied atomically to purchase order items and stock.';

create index if not exists purchase_order_receipts_order_id_idx
  on public.purchase_order_receipts (purchase_order_id);

comment on index public.purchase_order_receipts_order_id_idx is
  'Supports purchase-order receipt history lookups.';

revoke all on table public.purchase_order_receipts from public;

